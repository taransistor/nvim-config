vim.keymap.set("n", "<leader>s<CR>", function()
  vim.cmd("botright split")
  vim.cmd.term()
  vim.api.nvim_win_set_height(0, 12)
  vim.cmd("startinsert")
end)
vim.keymap.set("n", "<leader><CR>", function()
  vim.cmd.tabnew()
  vim.cmd.term()
  vim.cmd("startinsert")
end)
vim.keymap.set("t", "<Esc>", "<C-\\><C-n>")
